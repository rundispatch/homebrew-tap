#!/usr/bin/env bash
# Writes Formula/dispatch.rb for a Dispatch release: the latest one, or the
# version given. The checksums come from that release's SHA256SUMS.
#
#   scripts/update-formula.sh [version]
set -euo pipefail

cd "$(dirname "$0")/.."
version=${1:-$(gh release view -R rundispatch/dispatch --json tagName --jq .tagName)}
version=${version#v}
current=$(sed -n 's/^  version "\(.*\)"$/\1/p' Formula/dispatch.rb 2>/dev/null || true)
if [ "$version" = "$current" ]; then
  echo "Formula/dispatch.rb already installs $version."
  exit 0
fi

base="https://github.com/rundispatch/dispatch/releases/download/v$version"
sums=$(curl -fsSL "$base/SHA256SUMS")
macos=$(printf '%s\n' "$sums" | awk '$2 == "dispatch-macos-arm64.tar.gz" { print $1 }')
linux=$(printf '%s\n' "$sums" | awk '$2 == "dispatch-linux-x86_64.tar.gz" { print $1 }')
if [ ${#macos} -ne 64 ] || [ ${#linux} -ne 64 ]; then
  echo "SHA256SUMS for $version does not list both archives." >&2
  exit 1
fi

cat > Formula/dispatch.rb <<RUBY
# Generated by scripts/update-formula.sh from the v$version release's SHA256SUMS.
class Dispatch < Formula
  desc "Checks whether coding-agent work still holds against the current code"
  homepage "https://rundispatch.sh"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/dispatch-macos-arm64.tar.gz"
      sha256 "$macos"
    end
  end

  on_linux do
    on_intel do
      url "$base/dispatch-linux-x86_64.tar.gz"
      sha256 "$linux"
    end
  end

  def install
    bin.install "dispatch"
  end

  def caveats
    <<~EOS
      Dispatch needs Git, and the tools your project's own checks use.
      Get started: cd your-project && dispatch start
      Docs: https://rundispatch.sh/docs
    EOS
  end

  test do
    assert_equal "dispatch #{version}", shell_output("#{bin}/dispatch version").strip
  end
end
RUBY
echo "Formula/dispatch.rb now installs $version."
